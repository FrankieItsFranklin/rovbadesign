// Polish plural: 1 projekt, 2–4 projekty (but 12–14 projektów), otherwise projektów.
const projekty = (n: number) => {
  if (n === 1) return "projekt";
  const tens = n % 100;
  return n % 10 >= 2 && n % 10 <= 4 && (tens < 12 || tens > 14) ? "projekty" : "projektów";
};

